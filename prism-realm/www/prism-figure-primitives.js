/**
 * PRISM REALM — Primitivas y plantillas de figuras (sin three.js).
 * Cada figura es una lista de partes sólidas. Roles de color: A, B, C, D (paleta del nivel) y W (blanco fijo).
 */

const TAU = Math.PI * 2;

// Constructores de partes. Ejes locales: Y arriba, la cara frontal mira a +Z.
export const E = (p, r, col, rot) => ({ k: 'e', p, s: r, col, rot: rot || [0, 0, 0] });                  // elipsoide
export const B = (p, h, col, rot, rr) => ({ k: 'b', p, s: h, col, rot: rot || [0, 0, 0], rr: rr ?? 0.06 }); // caja redondeada
export const T = (p, R, r, col, rot) => ({ k: 't', p, s: [R, r], col, rot: rot || [0, 0, 0] });          // toro (anillo en plano XY)
export const Y = (p, rad, hh, col, rot) => ({ k: 'y', p, s: [rad, hh], col, rot: rot || [0, 0, 0] });    // cilindro vertical
export const C = (a, b, r, col, rot) => {                                                                   // cápsula entre a y b
  const m = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2];
  return {
    k: 'c', p: m,
    a: [a[0] - m[0], a[1] - m[1], a[2] - m[2]],
    b: [b[0] - m[0], b[1] - m[1], b[2] - m[2]],
    s: [r], col, rot: rot || [0, 0, 0]
  };
};

